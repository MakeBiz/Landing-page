#!/bin/bash
# Перенос нового сайта на боевой домен. Запускать ТОЛЬКО по команде Антона.
# Что делает: собирает site-v2/ (боевые адреса), кладёт туда картинки, видео и шрифты из превью v2/ и создаёт .v2-live.
# После публикации сервер отдаёт новые страницы из site-v2/, включает 301 со старых адресов и оборачивает новости
# и страницы-решения в новый дизайн. Старые файлы в корне не удаляются.
# Откат: переименовать .v2-live (например в .v2-off) и опубликовать, сайт вернётся к старым страницам.
set -e
SITE="$(cd "$(dirname "$0")/../.." && pwd)"; cd "$SITE"
bash .seo/v2/build_all.sh live
mkdir -p site-v2/img site-v2/media site-v2/assets
cp -R v2/img/. site-v2/img/
cp -R v2/media/. site-v2/media/
cp v2/assets/*.woff2 site-v2/assets/
date -u +%FT%TZ > .v2-live
echo "готово: site-v2 собран, .v2-live создан. Дальше .publish-request"
