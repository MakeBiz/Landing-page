def main():
    h = io.open(F, encoding='utf-8').read()
    before = h
    done = skipped = 0
    for old, new, n in PAIRS:
        # сначала смотрим на новый текст: часть новых строк содержит старую внутри себя
        # («IT-компания полного цикла» -> «... в ОАЭ»), и без этой проверки второй запуск допишет хвост ещё раз
        if h.count(new) >= n:
            skipped += 1
            continue
        c = h.count(old)
        if c == 0:
            raise SystemExit('НЕ НАЙДЕНО и не заменено ранее: %s' % old[:70])
        if c != n:
            raise SystemExit('ожидалось %d вхождений, найдено %d: %s' % (n, c, old[:70]))
        h = h.replace(old, new)
        done += 1
    if h != before:
        io.open(F, 'w', encoding='utf-8').write(h)
    print('%s: заменено %d, уже было %d' % (F, done, skipped))


if __name__ == '__main__':
    main()
